const hm = (min: number, lang: FLang) => {
  const h = Math.floor(min / 60)
  const m = Math.round(min % 60)
  if (lang === 'ar') return h && m ? `${h} س و ${m} دق` : h ? `${h} س` : `${m} دق`
  return h && m ? `${h} h ${String(m).padStart(2, '0')}` : h ? `${h} h` : `${m} min`
}

